import { createRequire } from 'node:module';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
const require=createRequire(process.argv[2]+'/package.json');
const {chromium}=require('playwright');
const base='http://127.0.0.1:5175';
const fixture=JSON.parse(readFileSync('.sites-runtime/browser-fixture.json','utf8').replace(/^\uFEFF/,''));
mkdirSync('.sites-runtime/browser-qa',{recursive:true});
const browser=await chromium.launch({headless:true,channel:'msedge'});
const page=await browser.newPage({viewport:{width:1440,height:1000}});
const errors=[];
page.on('pageerror',error=>errors.push(error.message));
try{
  await page.goto(base);
  await page.getByLabel('E-mail',{exact:true}).fill(fixture.email);
  await page.getByLabel('Senha',{exact:true}).fill(fixture.password);
  await page.getByRole('button',{name:'Entrar',exact:true}).click();
  await page.getByRole('button',{name:'Planejar aposentadoria'}).click();
  await page.getByLabel('Aporte mensal confirmado (R$)').fill('1500');
  await page.getByLabel('Usar dados fictícios para demonstração.',{exact:false}).check();
  await page.getByLabel('Autorizo o processamento do perfil derivado, capital, aporte, prazo e meta no motor.',{exact:false}).check();
  await page.getByRole('button',{name:'Calcular planejamento',exact:true}).click();
  await page.getByRole('button',{name:'Calculando cenários...',exact:true}).waitFor({state:'hidden',timeout:90000});
  await page.getByRole('heading',{name:'Resultado demonstrativo'}).waitFor({timeout:90000});
  await page.screenshot({path:'.sites-runtime/browser-qa/planner-desktop.png',fullPage:true});
  const chart=page.locator('.scenario-chart .recharts-wrapper > svg.recharts-surface');
  await chart.waitFor();
  if(await chart.count()!==1 || await chart.locator('path.recharts-area-curve').count()<3)throw new Error('Gráfico não renderizado.');
  const tableCount=await page.locator('.planner-table tbody tr').count();
  if(tableCount<3)throw new Error('Carteiras não renderizadas.');
  await page.reload();
  await page.getByRole('heading',{name:'Resultado demonstrativo'}).waitFor();
  if(await page.getByRole('checkbox',{name:'Autorizo o processamento',exact:false}).isChecked())throw new Error('Autorização foi marcada automaticamente.');
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:'.sites-runtime/browser-qa/planner-mobile.png',fullPage:true});
  const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth);
  if(overflow)throw new Error('Página mobile ultrapassa a largura.');
  page.once('dialog',dialog=>dialog.accept());
  await page.getByRole('button',{name:'Excluir',exact:true}).click();
  await page.getByRole('heading',{name:'Resultado demonstrativo'}).waitFor({state:'hidden'});
  if(errors.length)throw new Error(errors.join('\n'));
  const report={desktop:true,mobile:true,chart:true,tableRows:tableCount,restoredAfterReload:true,consentUncheckedAfterReload:true,deletion:true,pageErrors:errors};
  writeFileSync('.sites-runtime/browser-qa/report.json',JSON.stringify(report,null,2));
  console.log(JSON.stringify(report));
  const response=await page.request.delete(base+'/api/account',{headers:{Origin:base},data:{password:fixture.password}});
  if(!response.ok())throw new Error('Falha ao excluir a conta fictícia de teste.');
}catch(error){
  await page.screenshot({path:'.sites-runtime/browser-qa/failure.png',fullPage:true});
  console.log((await page.locator('body').innerText()).slice(0,2000));
  console.log('page errors',errors);
  throw error;
}finally{await browser.close();}
